// Run only against a disposable seeded database, with QA_UI_URL and QA_SEED_PASSWORD.
const assert = require('node:assert/strict')
const path = require('node:path')
const { chromium } = require('playwright')

async function run() {
  assert(process.env.QA_UI_URL && process.env.QA_SEED_PASSWORD)
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    const context = await browser.newContext({ baseURL: process.env.QA_UI_URL, viewport: { width: 375, height: 812 } })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', (e) => errors.push(e.message))
    async function data(method, url, payload) {
      const res = await context.request[method]('/api/v1' + url, payload ? { data: payload } : {})
      assert(res.ok(), `${method} ${url}: ${res.status()} ${await res.text()}`)
      return (await res.json()).data
    }
    const login = (role) => data('post', '/auth/login', { email: role + '@sunpower.test', password: process.env.QA_SEED_PASSWORD })
    const screenshot = async (name) => {
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile overflow')
      if (process.env.QA_SCREENSHOT_DIR) await page.screenshot({ path: path.join(process.env.QA_SCREENSHOT_DIR, name + '.png'), fullPage: true })
    }
    await login('sales')
    const enquiry = await data('post', '/public/enquiries', {
      name: 'Quick form customer', phone: '9876543291', address: 'QA roof', pincode: '560001', requested_kw: 3, system_type: 'ON_GRID',
    })
    await page.goto('/leads/' + enquiry.lead_id)
    await page.getByRole('button', { name: 'Log Call', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'Choose an outcome' }).waitFor()
    await page.getByRole('button', { name: 'Ready for a survey', exact: true }).click()
    await page.getByRole('button', { name: 'Yes', exact: true }).click()
    await page.getByRole('button', { name: '40', exact: true }).click()
    await page.getByRole('button', { name: '3000', exact: true }).click()
    await screenshot('quick-call-mobile')
    const saved = page.waitForResponse((r) => r.url().endsWith('/calls') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Log Call', exact: true }).click()
    assert.equal((await saved).status(), 201)
    const row = await data('get', '/leads/' + enquiry.lead_id)
    assert.equal(row.calls[0].outcome, 'Ready for a survey')
    assert.equal(row.calls[0].monthly_bill_paise, 300000)
    assert.equal(row.calls[0].shadow_free_area_sqm, 40)
    assert.equal(row.calls[0].grid_suitable, true)
    await page.getByRole('button', { name: 'Schedule survey', exact: true }).click()
    let dialog = page.getByRole('dialog')
    await dialog.getByLabel('Surveyor', { exact: true }).waitFor()
    assert.equal(await dialog.getByLabel('Lead', { exact: true }).inputValue(), String(enquiry.lead_id))
    assert((await dialog.innerText()).includes('9876543291'))
    await dialog.getByLabel('Search surveyor').fill('does-not-exist')
    await dialog.getByText('No matching results.', { exact: false }).waitFor()
    await dialog.getByLabel('Search surveyor').fill('Demo')
    const surveyor = await dialog.getByRole('option', { name: /Demo Surveyor/ }).getAttribute('value')
    await dialog.getByLabel('Surveyor', { exact: true }).selectOption(surveyor)
    await dialog.getByLabel('Visit time').fill('2026-12-01T10:00')
    await screenshot('survey-picker-mobile')
    await dialog.getByRole('button', { name: 'Schedule survey', exact: true }).click()
    await page.waitForURL(/\/surveys\/\d+$/)
    const surveyId = page.url().split('/').at(-1)
    await login('surveyor')
    const upload = await context.request.post(`/api/v1/surveys/${surveyId}/photos`, { multipart: {
      file: { name: 'roof.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jWZkAAAAASUVORK5CYII=', 'base64') },
    } })
    assert(upload.ok())
    await data('post', `/surveys/${surveyId}/submit`, { roof_direction: 'South', tilt_degrees: 20, cable_distance_m: 10 })
    await login('director')
    await data('post', `/surveys/${surveyId}/approve`, { note: 'QA approved' })
    await page.goto('/quotes')
    await page.getByRole('button', { name: 'Create quote', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('option', { name: /Quick form customer/ }).waitFor({ state: 'attached' })
    await dialog.getByLabel('Approved customer', { exact: true }).selectOption(String(enquiry.lead_id))
    const pkg = await dialog.getByRole('option', { name: /^On-Grid 3 kW/ }).getAttribute('value')
    await dialog.getByLabel('Package', { exact: true }).selectOption(pkg)
    await dialog.getByLabel('Valid until').fill('2026-12-20')
    await dialog.getByRole('button', { name: 'Create quote', exact: true }).click()
    await page.waitForURL(/\/quotes\/\d+$/)
    const quoteId = page.url().split('/').at(-1)
    await data('post', `/quotes/${quoteId}/send`)
    const order = await data('post', `/quotes/${quoteId}/accept`)
    await data('post', `/orders/${order.id}/payments`, { amount_paise: order.advance_min_paise, method: 'CASH' })
    await data('post', `/orders/${order.id}/confirm`)
    await page.goto('/invoices')
    await page.getByRole('button', { name: 'Create invoice', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('option', { name: /Quick form customer/ }).waitFor({ state: 'attached' })
    await dialog.getByLabel('Customer order', { exact: true }).selectOption(String(order.id))
    await dialog.getByRole('button', { name: 'Create invoice', exact: true }).click()
    await page.waitForURL(/\/invoices\/\d+$/)
    const job = (await data('get', '/installs')).find((j) => j.order_id === order.id)
    await login('support')
    await page.goto('/installs/' + job.id)
    await page.getByRole('option', { name: /Demo Crew/ }).waitFor({ state: 'attached' })
    const crewId = await page.getByRole('option', { name: /Demo Crew/ }).getAttribute('value')
    await page.getByLabel('Crew lead', { exact: true }).selectOption(crewId)
    await page.getByRole('checkbox', { name: /Demo Crew/ }).check()
    await page.getByLabel('Start', { exact: true }).fill('2026-12-02T10:00')
    await page.getByLabel('End', { exact: true }).fill('2026-12-02T12:00')
    await screenshot('crew-picker-mobile')
    const scheduled = page.waitForResponse((r) => r.url().endsWith('/schedule') && r.request().method() === 'PATCH')
    await page.getByRole('button', { name: 'Save schedule' }).click()
    assert.equal((await scheduled).status(), 200)
    const ticket = await data('post', '/tickets', { serial_no: 'INV-OLD-2024-001', fault_code: 'QA', description: 'QA assignment check' })
    await page.goto('/tickets')
    await page.getByText(ticket.number, { exact: true }).first().click()
    await page.getByText('Edit assignment and priority', { exact: true }).click()
    await page.getByRole('option', { name: /Demo Support/ }).waitFor({ state: 'attached' })
    const staffId = await page.getByRole('option', { name: /Demo Support/ }).getAttribute('value')
    await page.getByLabel('Assigned staff', { exact: true }).selectOption(staffId)
    const assigned = page.waitForResponse((r) => r.url().endsWith('/tickets/' + ticket.id) && r.request().method() === 'PATCH')
    await page.getByRole('button', { name: 'Save changes' }).click()
    assert.equal((await assigned).status(), 200)
    assert.equal((await data('get', '/tickets/' + ticket.id)).assigned_to_id, Number(staffId))
    await login('warehouse')
    await page.goto('/inventory')
    await page.getByRole('button', { name: 'Receive stock' }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('option', { name: /Quantity only/ }).first().waitFor({ state: 'attached' })
    const productId = await dialog.getByRole('option', { name: /Quantity only/ }).first().getAttribute('value')
    await dialog.getByLabel('Product', { exact: true }).selectOption(productId)
    await dialog.getByLabel('Quantity', { exact: true }).fill('1')
    await dialog.getByLabel('Unit purchase cost', { exact: false }).fill('100')
    const received = page.waitForResponse((r) => r.url().endsWith('/stock/receive'))
    await dialog.getByRole('button', { name: 'Receive stock' }).click()
    assert.equal((await received).status(), 200)
    await dialog.waitFor({ state: 'hidden' })
    let releaseChoices
    const choiceGate = new Promise((resolve) => { releaseChoices = resolve })
    await page.route('**/api/v1/products?*', async (route) => {
      await choiceGate
      await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'UNAVAILABLE', message: 'Choices temporarily unavailable', details: [] } }) })
    })
    await page.getByRole('button', { name: 'Receive stock', exact: true }).click()
    await dialog.getByText('Loading choices…', { exact: true }).waitFor()
    assert(await dialog.getByRole('button', { name: 'Receive stock', exact: true }).isDisabled())
    releaseChoices()
    await dialog.getByRole('alert').filter({ hasText: 'Choices temporarily unavailable' }).waitFor()
    assert(await dialog.getByRole('button', { name: 'Receive stock', exact: true }).isDisabled())
    await page.unroute('**/api/v1/products?*')
    await dialog.getByRole('button', { name: 'Retry choices' }).click()
    await dialog.getByRole('option', { name: /Quantity only/ }).first().waitFor({ state: 'attached' })
    assert.deepEqual(errors, [])
    console.log('PASS quick call, named survey, quote, invoice, crew, ticket and stock submissions at 375px')
  } finally { await browser.close() }
}
run().catch((e) => { console.error(e); process.exitCode = 1 })
